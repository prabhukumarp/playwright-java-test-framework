package com.prabhu.myapp.config.models;

public class PlaywrightViewport {
    private int width;
    private int height;

    // Getters and Setters

    public int getWidth() {
        return width;
    }

    public void setWidth(int width) {
        this.width = width;
    }

    public int getHeight() {
        return height;
    }

    public void setHeight(int height) {
        this.height = height;
    }
}
